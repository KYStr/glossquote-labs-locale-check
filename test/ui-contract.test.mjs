import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { resolveObjectURL } from 'node:buffer';
import { mountApp } from '../public/js/app.mjs';
import { mockDocument } from './mock-dom.mjs';

for (const [language, file] of [['zh-Hant', 'index.html'], ['en', 'en/index.html']]) {
  test(`${language}: offline actual app wiring from empty input to full local Blob (not browser)`, async () => {
    const html = await readFile(new URL(`../public/${file}`, import.meta.url), 'utf8');
    const { document, window, get } = mockDocument(html);
    const controller = mountApp(document, window);
    assert.equal(controller.snapshot().report, null);
    assert.equal(get('results').hidden, true);
    assert.equal(get('download-json').disabled, true);
    assert.equal(get('reference').value, '');
    get('reference').value = '{"a.b":"Hi {name}","a":{"b":"B"},"absent":"x"}';
    get('reference').dispatch('input');
    get('target').value = '{"a.b":"嗨 {user}","a":{"b":"譯文"},"extra":"e"}';
    get('target').dispatch('input');
    get('check-form').dispatch('submit');
    assert.equal(controller.snapshot().state, 'ready');
    assert.equal(get('results').hidden, false);
    assert.equal(get('download-json').disabled, false);
    assert.equal(get('issue-rows').children.length, 3);
    assert.equal(get('count-missing').textContent, '1');
    get('filter').value = 'missing'; get('filter').dispatch('change');
    assert.equal(get('issue-rows').children.length, 1);
    get('download-json').click();
    assert.equal(document.downloads.length, 1);
    assert.equal(document.downloads[0].filename, 'locale-check-report.json');
    const blob = resolveObjectURL(document.downloads[0].href);
    assert.deepEqual(JSON.parse(await blob.text()).issues.map(issue => issue.code), ['VARIABLE_MISMATCH', 'MISSING_KEY', 'EXTRA_KEY']);
    get('download-txt').click();
    assert.match(await resolveObjectURL(document.downloads[1].href).text(), /VARIABLE_MISMATCH/);
    assert.equal(get('report-text').value.endsWith('\n'), true);
    get('select-report').click(); assert.equal(get('report-text').selected, true);
    get('target').value = '{"x":false}'; get('target').dispatch('input');
    assert.equal(get('results').hidden, true);
    assert.equal(get('download-json').disabled, true);
    assert.equal(get('report-text').value, '');
    assert.equal(resolveObjectURL(document.downloads[0].href), undefined);
    get('check-form').dispatch('submit');
    assert.match(get('target-error').textContent, /TYPE/);
    assert.equal(document.activeElement, get('target'));
    assert.equal(get('target').attributes.get('aria-invalid'), 'true');
    get('clear-all').click();
    assert.equal(get('target').value, '');
    assert.equal(get('reference').value, '');
    get('load-example').click();
    get('check-form').dispatch('submit');
    assert.equal(controller.snapshot().report.counts.errors, 5);
    window.dispatch('pagehide');
    assert.equal(controller.snapshot().report, null);
    assert.equal(get('reference').value, '');
  });
  test(`${language}: hostile text is only text; example overwrite needs explicit confirmation (offline mock)`, async () => {
    const html = await readFile(new URL(`../public/${file}`, import.meta.url), 'utf8');
    const { document, window, get } = mockDocument(html);
    const controller = mountApp(document, window);
    get('reference').value = '{"<img src=x onerror=bad>":"</script><script>fake</script>"}';
    get('reference').dispatch('input');
    get('target').value = '{}'; get('target').dispatch('input');
    get('check-form').dispatch('submit');
    assert.match(get('issue-rows').textContent, /<img src=x onerror=bad>/);
    assert.match(get('issue-rows').textContent, /<script>fake<\/script>/);
    const nodes = node => [node, ...node.children.flatMap(nodes)];
    assert.equal(nodes(get('issue-rows')).some(element => ['IMG', 'SCRIPT'].includes(element.tagName)), false);
    get('load-example').click();
    assert.equal(get('example-confirm').hidden, false);
    assert.equal(controller.snapshot().report, null);
    assert.equal(get('check').disabled, true);
    assert.match(get('reference').value, /onerror/);
    get('keep-example').click();
    assert.match(get('reference').value, /onerror/);
    get('load-example').click(); get('accept-example').click();
    assert.match(get('reference').value, /Demo Brand/);
    get('syntax').value = 'double'; get('syntax').dispatch('change');
    assert.equal(controller.snapshot().report, null);
    window.dispatch('pagehide');
  });
}
